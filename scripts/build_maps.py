#!/usr/bin/env python3
"""Build the website's two maps from Natural Earth (public domain).

    python3 scripts/build_maps.py <ne_50m_admin_0_countries.geojson> <ne_50m_lakes.geojson>

Source files: https://github.com/nvkelso/natural-earth-vector/tree/master/geojson
Writes frontend/src/components/maps/geo.ts: SVG path strings for the country
and lake outlines, and projected positions for the places each map marks.
Equirectangular projection, scaled by cos(central latitude) — accurate
enough at these latitudes, and it keeps the output small. Re-run to change a
frame or add a place; never hand-edit geo.ts.
"""
import json
import math
import sys
from pathlib import Path

COUNTRIES = ["Uganda", "Kenya", "United Republic of Tanzania", "Rwanda", "Burundi",
             "South Sudan", "Democratic Republic of the Congo", "Ethiopia", "Somalia"]
LAKES = ["Lake Victoria", "Lake Albert", "Lake Kyoga", "Lake Edward", "Lake Turkana", "Lake Tanganyika"]

# Places use real coordinates (lat, lon).
PLACES = {
    "kampala": (0.3476, 32.5825), "nairobi": (-1.2864, 36.8172), "mombasa": (-4.0435, 39.6682),
    "dar": (-6.7924, 39.2083), "kigali": (-1.9441, 30.0619), "juba": (4.8594, 31.5713),
    "malaba": (0.6364, 34.2775), "mutukula": (-0.99, 31.42), "elgon": (1.134, 34.55),
    "mbale": (1.0757, 34.1755),
}

# Corridors as road waypoints (lat, lon), generalised: what matters is the
# order of the towns, not every bend.
ROUTES = {
    "northern": [(-4.0435, 39.6682), (-3.396, 38.556), (-1.2864, 36.8172), (-0.3031, 36.08),
                 (0.5143, 35.2698), (0.6364, 34.2775), (0.4244, 33.2041), (0.3476, 32.5825)],
    "central": [(-6.7924, 39.2083), (-6.8278, 37.6591), (-6.163, 35.7516), (-4.816, 34.75),
                (-4.21, 33.18), (-2.5164, 32.9175), (-1.3317, 31.8122), (-0.99, 31.42),
                (-0.3338, 31.7341), (0.3476, 32.5825)],
    "west": [(0.3476, 32.5825), (-0.6072, 30.6545), (-1.9441, 30.0619)],
    "north": [(0.3476, 32.5825), (2.7724, 32.299), (3.596, 32.063), (4.8594, 31.5713)],
}

FRAMES = {
    # name: (lon_min, lon_max, lat_min, lat_max, width)
    "eastAfrica": (28.4, 41.6, -8.2, 5.8, 1000),
    "uganda": (29.3, 35.6, -1.7, 4.4, 1000),
}


def rings(geom):
    if geom["type"] == "Polygon":
        yield from geom["coordinates"]
    elif geom["type"] == "MultiPolygon":
        for poly in geom["coordinates"]:
            yield from poly


def make(frame):
    lon0, lon1, lat0, lat1, width = frame
    k = math.cos(math.radians((lat0 + lat1) / 2))
    sx = width / ((lon1 - lon0) * k)
    height = round((lat1 - lat0) * sx)

    def p(lat, lon):
        return round((lon - lon0) * k * sx, 1), round((lat1 - lat) * sx, 1)

    def path(geom):
        out = []
        for ring in rings(geom):
            pts, last = [], None
            for lon, lat in ring:
                # Clamp to the frame (plus a small margin): outlines of large
                # neighbours stay correct where they show, and cost nothing
                # where they do not.
                lon = min(max(lon, lon0 - 0.3), lon1 + 0.3)
                lat = min(max(lat, lat0 - 0.3), lat1 + 0.3)
                xy = p(lat, lon)
                if last is None or abs(xy[0] - last[0]) + abs(xy[1] - last[1]) >= 1.6:
                    pts.append(xy)
                    last = xy
            if len(pts) > 2:
                out.append("M" + "L".join(f"{x},{y}" for x, y in pts) + "Z")
        return "".join(out)

    return p, path, height


def main():
    countries = json.load(open(sys.argv[1]))["features"]
    lakes = json.load(open(sys.argv[2]))["features"]
    blocks = []
    for name, frame in FRAMES.items():
        p, path, height = make(frame)
        cs = {f["properties"]["ADMIN"]: path(f["geometry"]) for f in countries if f["properties"]["ADMIN"] in COUNTRIES}
        ls = {f["properties"]["name"]: path(f["geometry"]) for f in lakes if f["properties"].get("name") in LAKES}
        places = {k: p(*v) for k, v in PLACES.items()}
        routes = {k: "M" + "L".join(f"{x},{y}" for x, y in (p(*w) for w in v)) for k, v in ROUTES.items()}
        blocks.append(f"export const {name} = " + json.dumps({
            "width": frame[4], "height": height,
            "countries": cs, "lakes": ls, "places": places, "routes": routes,
        }, separators=(",", ":")) + " as const;\n")

    out = Path(__file__).resolve().parent.parent / "frontend/src/components/maps/geo.ts"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "/* Generated by scripts/build_maps.py from Natural Earth (public domain).\n"
        "   Do not edit by hand: change the script and re-run it. */\n\n" + "\n".join(blocks)
    )
    print(out, out.stat().st_size // 1024, "KB")


if __name__ == "__main__":
    main()
